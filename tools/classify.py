def classify(r):
    ch = (r.get("chapter") or "").strip()
    if ch in CANON:
        return CANON[ch]
    text = r["stem"] + " " + " ".join(o[1] for o in r["options"])
    best = None
    best_hits = 0
    for chapter, kws in RULES:
        hits = sum(text.count(k) for k in kws)
        if hits > best_hits:
            best, best_hits = chapter, hits
    if best:
        return best
    return "11 待归类"


rows = json.load(open("work/bank_canon.json", encoding="utf-8"))
for r in rows:
    r["chapter_final"] = classify(r)

rows.sort(key=lambda r: (r["chapter_final"], -len(r["stem"])))
